import numpy as np

def generate_ai_conclusion(feature_importances, features, mae, mape, accuracy):
    """
    Генерирует динамический вывод на основе весов признаков и метрик.
    """
    top_idx = np.argmax(feature_importances)
    top_feature = features[top_idx]
    top_share = feature_importances[top_idx] * 100
    
    conclusion = f"**Вывод нейросети:** Анализ весов показал, что **{top_share:.1f}%** влияния на прогноз оказывает фактор «{top_feature}». "
    
    if top_feature == "День месяца":
        conclusion += "Это подтверждает гипотезу о том, что бизнес сильно зависит от календарных платежей (налоги до 28-го числа, авансы по зарплате). Модель выучила эти паттерны."
    elif top_feature == "День недели":
        conclusion += "Модель выявила сильную недельную сезонность. Поступления и списания сконцентрированы в рабочие дни, в выходные — затишье."
    elif top_feature == "Предыдущий баланс":
        conclusion += "Алгоритм опирается на инерцию Cash Flow. Текущий остаток сильно коррелирует с завтрашним."
    elif top_feature == "Скользящее среднее":
        conclusion += "Модель сглаживает случайные выбросы, опираясь на общий тренд за последнюю неделю."
    else:
        conclusion += "Модель нашла сложную нелинейную взаимосвязь между этим признаком и движением денежных средств."
        
    conclusion += f"\n\n**Оценка качества:** Точность попадания в 10% интервал составляет **{accuracy:.1f}%**. "
    conclusion += f"Средняя абсолютная ошибка (MAE) — **{mae:,.0f} руб.** "
    
    if accuracy > 80:
        conclusion += f"Модель показывает высокую надежность для финансового прогнозирования."
    elif accuracy > 60:
        conclusion += f"Модель улавливает основные тренды, но рекомендует учитывать фактор волатильности."
    else:
        conclusion += f"Высокая волатильность данных. Рекомендуется загрузить больше истории для стабилизации прогноза."
        
    return conclusion